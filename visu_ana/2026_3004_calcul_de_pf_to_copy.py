# --- Grille physique : fc ≥ 0 et fy ≥ 0 ---
def make_grid(fck, cov_fck, fyk, cov_fyk, size_visu, n):
    """
    Retourne n*n points (u1, u2) avec fc ≥ 0 et fy ≥ 0.
    - fc lognormale : toujours > 0, pas de contrainte sur u1
    - fy normale    : fy ≥ 0  →  u2 ≥ -mu_fy / sigma_fy
    """
    dist_fy  = loi_fy(fyk, cov_fyk)
    mu_fy    = dist_fy.getMean()[0]
    sigma_fy = dist_fy.getStandardDeviation()[0]
    u2_min   = max(-size_visu, -mu_fy / sigma_fy)   # seuil fy = 0

    u1_vals  = np.linspace(-size_visu, size_visu, n)
    u2_vals  = np.linspace(u2_min, size_visu, n)
    U1g, U2g = np.meshgrid(u1_vals, u2_vals)
    return np.column_stack([U1g.ravel(), U2g.ravel()])

