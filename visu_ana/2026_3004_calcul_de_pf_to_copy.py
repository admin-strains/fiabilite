# --- Échantillonnage de points sur la frontière g_ana = 0 (toutes les branches) ---
def sample_frontier(calc, n_scan=100):
    """
    Pour chaque u1, scanne u2 et trouve TOUS les zéros de g_ana = 0
    (détecte toutes les branches par changements de signe successifs).
    Utilise les globales : size_visu, fyk, cov_fyk, SIGMA.
    n_scan : résolution du scan u2 pour détecter les changements de signe.
    """
    if cov_fyk is None:
        u2_min = -(fyk / SIGMA + 1.645)
    else:
        u2_min = -1.0 / cov_fyk
    u2_low = max(-size_visu, u2_min)

    pts = []
    u2_scan = np.linspace(u2_low, size_visu, n_scan)
    for u1 in np.linspace(-size_visu, size_visu, 40):
        g_vals = [calc.g_ana([u1, u2]) for u2 in u2_scan]
        for i in range(len(u2_scan) - 1):
            if g_vals[i] * g_vals[i+1] < 0:
                u2_star = brentq(
                    lambda u2: calc.g_ana([u1, u2]), u2_scan[i], u2_scan[i+1])
                pts.append([u1, u2_star])
    return np.array(pts) if pts else np.zeros((0, 2))

